#!/usr/bin/env python3
"""Print WindowsTimeZones.swift, the IANA -> Windows time zone table.

Every CLDR windowsZones.xml mapZone, one row per Windows ID with its
territory 001 zone first, plus IANA's canonical name where it differs from
CLDR's (Asia/Kolkata for Asia/Calcutta, from common/bcp47/timezone.xml):
macOS reports IANA names.

The answer file's TimeZone has to name a zone the Windows image knows, so
use a CLDR release whose Windows IDs every supported Windows 11 image has.
release-49 added three 2026 Canadian zones (British Columbia, Alberta,
Manitoba Standard Time); release-48 maps those cities to the older zones.

usage: generate-windows-time-zones.py CLDR_TAG windowsZones.xml timezone.xml \
           > apps/macos/Sources/BridgeVMControl/WindowsTimeZones.swift
"""
import sys
import xml.etree.ElementTree as ET

tag, zones_path, bcp47_path = sys.argv[1:]
iana = {}
for zone in ET.parse(bcp47_path).iter("type"):
    aliases = zone.get("alias", "").split()
    if aliases and zone.get("iana"):
        iana[aliases[0]] = zone.get("iana")
rows, seen = {}, set()
for zone in ET.parse(zones_path).iter("mapZone"):
    names = rows.setdefault(zone.get("other"), [])
    for cldr in zone.get("type").split():
        for name in filter(None, (cldr, iana.get(cldr))):
            if name not in seen:
                seen.add(name)
                names.append(name)
print(f"""// Generated by scripts/generate-windows-time-zones.py from CLDR {tag}
// (common/supplemental/windowsZones.xml, common/bcp47/timezone.xml); do not edit.

/// IANA time zone names to Windows time zone IDs: every CLDR mapping, one row
/// per Windows zone with its territory 001 zone first.
enum WindowsTimeZones {{
    static let byIANA: [String: String] = Dictionary(
        rows.flatMap {{ windows, names in
            names.split(separator: " ").map {{ (String($0), windows) }}
        }},
        uniquingKeysWith: {{ first, _ in first }})

    private static let rows: [(String, String)] = [""")
for windows, names in rows.items():
    print(f'        ("{windows}", "{" ".join(names)}"),')
print("""    ]
}""")
