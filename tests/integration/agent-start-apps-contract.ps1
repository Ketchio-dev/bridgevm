)
foreach ($id in $refused) { if (Test-BvStartAppId $id) { throw "an unsafe AppID was taken: [$id]" } }

# 2. The list: one row per AppID (case-insensitively), sorted by name, only AppIDs STARTAPP takes, no
# empty or overlong names, names and AppIDs round-trip through base64 UTF-8.
$script:startApps = {
    App 'Notepad++' "$guid\Notepad++\notepad++.exe"
    App 'Calculator' 'Microsoft.WindowsCalculator_8wekyb3d8bbwe!App'
    App 'Calculator again' 'MICROSOFT.WINDOWSCALCULATOR_8WEKYB3D8BBWE!APP'
    App ('  ' + $hangul + ' Talk ') "$guid\$hangul\KakaoTalk.exe"
    App 'Command Prompt' 'C:\Windows\System32\cmd.exe'
    App 'Website' 'https://example.com/'
    App 'Injected' 'x" & calc & "'
    App '   ' 'Microsoft.Windows.Explorer'
    App ('n' * 257) 'MSEdge'
    App 'File Explorer' 'Microsoft.Windows.Explorer'
}
$rows = Rows (Get-BvStartApps)
# The guest's culture orders Hangul before or after Latin; the Latin names keep their order either way.
$expected = @('Calculator|Microsoft.WindowsCalculator_8wekyb3d8bbwe!App', 'File Explorer|Microsoft.Windows.Explorer',
    "Notepad++|$guid\Notepad++\notepad++.exe", ($hangul + " Talk|$guid\$hangul\KakaoTalk.exe"))
$actual = @($rows | ForEach-Object { $_.Name + '|' + $_.AppID })
$latin = @($actual | Where-Object { $_ -cmatch '^[A-Za-z]' })
if ((@($actual | Sort-Object) -join "`n") -cne (@($expected | Sort-Object) -join "`n") -or ($latin -join "`n") -cne (@($expected[0..2]) -join "`n")) {
    throw ("list changed:`n" + ($actual -join "`n"))
}
$script:startApps = { }
$empty = Get-BvStartApps
if ($empty.Exit -ne 0 -or $empty.Out -cne '') { throw 'no apps is not an empty list' }

# 3. Bounds: at most 2000 apps and 512 KB, whole rows only.
$script:startApps = { foreach ($i in 1..2100) { App ('App {0:D4}' -f $i) ('Vendor.App{0:D4}_abc!App' -f $i) } }
$rows = Rows (Get-BvStartApps)
if ($rows.Count -ne 2000 -or $rows[0].Name -cne 'App 0001' -or $rows[1999].Name -cne 'App 2000') { throw "app cap: $($rows.Count)" }
$script:startApps = { foreach ($i in 1..2000) { App (('{0:D4}' -f $i) + ('x' * 250)) ("$guid\Vendor\" + ('{0:D4}' -f $i) + ('y' * 200) + '.exe') } }
$reply = Get-BvStartApps
$rows = Rows $reply
if ($reply.Out.Length -gt 512KB -or $rows.Count -lt 100 -or $rows.Count -ge 2000 -or -not $rows[-1].AppID.EndsWith('.exe')) { throw "byte cap: $($reply.Out.Length) bytes, $($rows.Count) rows" }

# 4. A failing Get-StartApps answers unavailable; the detail goes to the log only.
$script:startApps = { throw 'start layout detail' }
$reply = Get-BvStartApps
if ($reply.Exit -ne 1 -or $reply.Out -cne 'BVSTARTAPPS unavailable' -or -not ($script:logged -ccontains 'STARTAPPS failed: start layout detail')) { throw 'failed list not reported' }

# 5. STARTAPP: explorer.exe gets shell:AppsFolder\<AppID> as one quoted argument (no quote inside, none
# escaped), and nothing starts for anything that is not an AppID.
foreach ($id in @('Microsoft.WindowsCalculator_8wekyb3d8bbwe!App', "$guid\Notepad++\notepad++.exe", "$guid\Mozilla Firefox\firefox.exe")) {
    $script:started.Clear()
    $reply = Start-BvStartApp (B64 $id)
    if ($reply.Exit -ne 0 -or $reply.Out -cne 'BVSTARTAPP ok' -or $script:started.Count -ne 1) { throw "launch failed: $id" }
    $call = $script:started[0]
    if (-not $call.FilePath.EndsWith('explorer.exe') -or $call.Arguments.Count -ne 1) { throw "launch not one explorer argument: $id" }
    $argument = [string]$call.Arguments[0]
    if ($argument -cne ('"shell:AppsFolder\' + $id + '"') -or $argument.Split('"').Count -ne 3 -or $argument.EndsWith('\"')) { throw "launch argument changed: $argument" }
}
if ($IsWindows -or $PSVersionTable.PSEdition -eq 'Desktop') {
    $windows = [Environment]::GetFolderPath('Windows')
    if ($script:started[0].FilePath -cne [IO.Path]::Combine($windows, 'explorer.exe')) { throw "not the Windows folder's explorer: $($script:started[0].FilePath)" }
}
$script:started.Clear()
$invalidUtf8 = [Convert]::ToBase64String([byte[]](0x41, 0xC3, 0x28, 0x42))
foreach ($arg in @('', 'not base64!', 'QUJD RA==', ((B64 'Microsoft.WindowsCalculator_8wekyb3d8bbwe!App') + ' extra'), $invalidUtf8,
        (B64 'x" & calc & "'), (B64 'Microsoft.WindowsCalculator_8wekyb3d8bbwe!App,/root,C:\'), (B64 '..\..\Windows\System32\cmd.exe'),
        (B64 "Microsoft.WindowsCalculator_8wekyb3d8bbwe!App`r`nRUN Y21k"), (B64 'C:\Windows\System32\cmd.exe'), ('QUFB' * 1025))) {
    $reply = Start-BvStartApp $arg
    if ($reply.Exit -ne 1 -or $reply.Out -cne 'BVSTARTAPP refused') { throw "launch not refused: [$arg]" }
}
if ($script:started.Count -ne 0) { throw 'a refused launch started a process' }
$script:startFails = $true
$reply = Start-BvStartApp (B64 'MSEdge')
if ($reply.Exit -ne 1 -or $reply.Out -cne 'BVSTARTAPP failed' -or -not ($script:logged -ccontains 'STARTAPP failed: explorer detail')) { throw 'failed launch not reported' }
$script:startFails = $false

# 6. READY advertises both verbs with one marker, the app's only gate.
$readyTokens = (Get-BvReady $PSScriptRoot '') -split ' '
if (-not ($readyTokens -ccontains 'startapps')) { throw 'READY lacks startapps' }

# 7. The resident dispatch: STARTAPPS (its request ID ignored) and STARTAPP answer through Write-CommandResult.
$switches = $ast.FindAll({ param($node) $node -is [Management.Automation.Language.SwitchStatementAst] }, $true)
$main = @($switches | Where-Object { @($_.Clauses | Where-Object { $_.Item1.Extent.Text -ceq "'WINCLOSE'" }).Count -eq 1 })
if ($main.Count -ne 1) { throw 'expected one resident dispatch' }
$parts = @(foreach ($verb in @('STARTAPPS', 'STARTAPP')) {
    $clause = @($main[0].Clauses | Where-Object { $_.Item1.Extent.Text -ceq "'$verb'" })
    if ($clause.Count -ne 1) { throw "expected one $verb clause" }
    $clause[0].Item1.Extent.Text + ' ' + $clause[0].Item2.Extent.Text
})
$dispatch = [scriptblock]::Create('switch ($tok) { ' + ($parts -join "`n") + "`n default " + $main[0].Default.Extent.Text + ' }')
$writer = $ast.Find({ param($node) $node -is [Management.Automation.Language.FunctionDefinitionAst] -and $node.Name -eq 'Write-CommandResult' }, $true)
. ([scriptblock]::Create($writer.Extent.Text))
function Write-Line($Handle, [string]$Line, [string]$What) {
    if ($Handle -ne 123) { throw 'resident handle changed' }
    [void]$script:wire.Add($Line)
}
function Invoke-ResidentToken([string]$tok, [string]$arg) { $h = 123; . $dispatch }
$script:wire = New-Object 'System.Collections.Generic.List[string]'
$script:startApps = { App 'Calculator' 'Microsoft.WindowsCalculator_8wekyb3d8bbwe!App' }
Invoke-ResidentToken 'STARTAPPS' '12345678-1234-1234-1234-123456789abc'
Invoke-ResidentToken 'STARTAPP' (B64 'Microsoft.WindowsCalculator_8wekyb3d8bbwe!App')
Invoke-ResidentToken 'STARTAPP' (B64 'x" & calc & "')
$expectedWire = @(('OUT 0 ' + (B64 ((B64 'Calculator') + '|' + (B64 'Microsoft.WindowsCalculator_8wekyb3d8bbwe!App')))),
    ('OUT 0 ' + (B64 'BVSTARTAPP ok')), ('OUT 1 ' + (B64 'BVSTARTAPP refused')))
if (($script:wire.ToArray() -join '|') -cne ($expectedWire -join '|')) { throw ('resident wire mismatch: ' + ($script:wire.ToArray() -join '|')) }

# 8. The real Get-StartApps on Windows PowerShell 5.1, where the agent runs: well formed either way.
if ($PSVersionTable.PSEdition -eq 'Desktop') {
    Remove-Item Function:\Get-StartApps
    if (Get-Command Get-StartApps -ErrorAction SilentlyContinue) {
        $reply = Get-BvStartApps
        if ($reply.Exit -eq 0) {
            $rows = Rows $reply
            foreach ($row in $rows) { if (-not (Test-BvStartAppId $row.AppID) -or $row.Name.Length -eq 0) { throw "native row malformed: $($row.AppID)" } }
            Write-Output "native: $($rows.Count) apps"
        } elseif ($reply.Out -cne 'BVSTARTAPPS unavailable') { throw "native failure malformed: $($reply.Out)" }
        else { Write-Output 'native: unavailable' }
    } else { Write-Output 'native: no Get-StartApps' }
}
