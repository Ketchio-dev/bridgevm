# STARTAPPS / STARTAPP (bvagent.ps1 Get-BvStartApps, Start-BvStartApp): the Start menu's apps leave
# the agent as one <b64(name)>|<b64(AppID)> line each, one per AppID, sorted by name, within 2000 apps
# and 512 KB, and only with AppIDs STARTAPP takes; a failing Get-StartApps answers
# `BVSTARTAPPS unavailable` with exit 1. STARTAPP takes only an AppID shaped like Get-StartApps'
# (AUMIDs, {GUID}\path\x.exe) and hands it to explorer.exe as one quoted argument; anything else is
# refused before any process starts. READY advertises `startapps`, and the resident dispatch frames both
# replies as a RUN's. Get-StartApps and Start-Process are stubbed; on Windows PowerShell 5.1 the real
# Get-StartApps runs once and whatever the runner has must come out well formed.
$ErrorActionPreference = 'Stop'
$tokens = $null; $errors = $null
$assets = Join-Path $PSScriptRoot '../../scripts/win-assets'
$agentPath = Join-Path $assets 'bvagent.ps1'
$ast = [Management.Automation.Language.Parser]::ParseFile($agentPath, [ref]$tokens, [ref]$errors)
if ($errors.Count -ne 0) { throw 'resident agent parse failure' }
$section = @($ast.EndBlock.Statements | Where-Object {
    ($_ -is [Management.Automation.Language.AssignmentStatementAst] -and $_.Left.Extent.Text -like '$script:BvStartApps*') -or
    ($_ -is [Management.Automation.Language.FunctionDefinitionAst] -and $_.Name -in @('Test-BvStartAppId', 'Get-BvStartApps', 'Start-BvStartApp', 'Get-BvReady'))
})
if ($section.Count -ne 6) { throw "expected the two limits, Test-BvStartAppId, Get-BvStartApps, Start-BvStartApp and Get-BvReady, found $($section.Count)" }
foreach ($statement in $section) { . ([scriptblock]::Create($statement.Extent.Text)) }

$script:logged = New-Object 'System.Collections.Generic.List[string]'
function Log([string]$Message) { [void]$script:logged.Add($Message) }
$script:startApps = { @() }
function Get-StartApps { & $script:startApps }
$script:started = New-Object 'System.Collections.Generic.List[object]'
$script:startFails = $false
function Start-Process([string]$FilePath, [object]$ArgumentList, $ErrorAction) {
    if ($script:startFails) { throw 'explorer detail' }
    [void]$script:started.Add([pscustomobject]@{ FilePath = $FilePath; Arguments = @($ArgumentList) })
}
function B64([string]$Text) { [Convert]::ToBase64String([Text.Encoding]::UTF8.GetBytes($Text)) }
function Unb64([string]$Text) { [Text.Encoding]::UTF8.GetString([Convert]::FromBase64String($Text)) }
function App([string]$Name, [string]$Id) { [pscustomobject]@{ Name = $Name; AppID = $Id } }
function Rows($Reply) {
    if ($Reply.Exit -ne 0) { throw "list failed: $($Reply.Out)" }
    if ($Reply.Out.Length -eq 0) { return @() }
    return @($Reply.Out -split '\r?\n' | ForEach-Object {
        if ($_ -cnotmatch '^[A-Za-z0-9+/]+={0,2}\|[A-Za-z0-9+/]+={0,2}\z') { throw "malformed row: $_" }
        $parts = $_.Split('|')
        [pscustomobject]@{ Name = (Unb64 $parts[0]); AppID = (Unb64 $parts[1]) }
    })
}

